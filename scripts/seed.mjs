// Builds migrations/seed.sql from the original static site content (scripts/legacy-content.js),
// so the database starts with every bean, story, price and setting the site already had.
// Run with: npm run db:seed
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('./legacy-content.js', import.meta.url), 'utf8');
const ctx = {};
vm.runInNewContext(`${src}\n;this.out = { SHOP, I18N, BEANS, MENU };`, ctx);
const { SHOP, I18N, BEANS, MENU } = ctx.out;

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, row) => `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(q).join(', ')});`;
const piasters = (egp) => (egp == null ? null : Math.round(egp * 100));

const sql = ['-- generated by scripts/seed.mjs', 'PRAGMA foreign_keys = ON;'];
const productIds = {};
let pid = 0;

// coffees from the story book
BEANS.forEach((b, i) => {
  pid += 1;
  productIds[b.id] = pid;
  sql.push(insert('products', {
    id: pid, slug: b.id, kind: 'coffee',
    name_ar: b.ar.name, name_en: b.en.name,
    origin_ar: b.ar.origin, origin_en: b.en.origin,
    notes_ar: b.ar.notes, notes_en: b.en.notes,
    story_ar: JSON.stringify(b.ar.story), story_en: JSON.stringify(b.en.story),
    tip_ar: b.ar.pair || '', tip_en: b.en.pair || '',
    tag_ar: b.ar.tag || '', tag_en: b.en.tag || '',
    roasts: b.roasts.join(','), color: b.color,
    image: `/media/beans/${b.id}.webp`,
    in_book: 1, active: 1, sort: i + 1,
  }));
});

// menu items that are not in the book
const extraSlugs = { 'نسكافيه بلاك': 'nescafe-black', 'نسكافيه جولد': 'nescafe-gold', 'كوفي مكس': 'coffee-mix', 'كوفي شوب سادة': 'coffee-shop', 'كوفي شوب محوّج': 'coffee-shop' };
const extraNames = { 'coffee-shop': { ar: 'كوفي شوب', en: 'Coffee Shop Blend' } };
function productFor(item) {
  if (item.bean) return productIds[item.bean];
  const slug = extraSlugs[item.name.ar];
  if (!productIds[slug]) {
    pid += 1;
    productIds[slug] = pid;
    const name = extraNames[slug] || item.name;
    sql.push(insert('products', {
      id: pid, slug, kind: 'other', name_ar: name.ar, name_en: name.en,
      color: '#6E4022', image: '/media/bags.jpg', in_book: 0, active: 1, sort: 100 + pid,
    }));
  }
  return productIds[slug];
}

let itemId = 0;
const addItem = (productId, section, it, label = {}) => {
  itemId += 1;
  sql.push(insert('items', {
    id: itemId, product_id: productId, section,
    roasts: (it.roasts || []).join(','),
    label_ar: label.ar || '', label_en: label.en || '',
    price_125: piasters(it.prices[0]), price_250: piasters(it.prices[1]), price_1000: piasters(it.prices[2]),
    available: 1, sort: itemId,
  }));
};
MENU.plain.forEach((it) => addItem(productFor(it), 'plain', it));
MENU.spiced.forEach((it) => addItem(productFor(it), 'spiced', it));

// French coffee: the printed "flavored" row becomes one row per flavor so customers can pick one
const french = productIds.french;
addItem(french, 'french', MENU.french[0], { ar: 'بندق قطع', en: 'Hazelnut pieces' });
addItem(french, 'french', MENU.french[1], { ar: 'بندق سادة', en: 'Plain hazelnut' });
[['كراميل', 'Caramel'], ['توت', 'Berry'], ['كلاسيك', 'Classic'], ['شوكولاتة', 'Chocolate'], ['لوتس', 'Lotus']]
  .forEach(([ar, en]) => addItem(french, 'french', MENU.french[2], { ar, en }));

[
  ['حبوب كاملة من غير طحن', 'Whole beans, not ground'],
  ['ناعم للكنكة', 'Fine, for kanaka'],
  ['وسط للفلتر', 'Medium, for filter'],
  ['إسبريسو', 'Espresso'],
  ['خشن للفرنش برس', 'Coarse, for French press'],
].forEach(([ar, en], i) => sql.push(insert('grinds', { id: i + 1, name_ar: ar, name_en: en, active: 1, sort: i + 1 })));

const settings = {
  shop_phone: SHOP.phone, shop_whatsapp: SHOP.whatsapp,
  instagram: SHOP.instagram, facebook: SHOP.facebook, tiktok: SHOP.tiktok, maps_url: SHOP.mapsUrl,
  address_ar: SHOP.address.ar, address_en: SHOP.address.en, hours_ar: SHOP.hours.ar, hours_en: SHOP.hours.en,
  pickup_enabled: '1', delivery_enabled: '1',
  delivery_fee: '3000',            // 30 EGP placeholder, owner sets the real fee in admin
  free_delivery_over: '0',         // 0 = never free
  delivery_area_ar: '', delivery_area_en: '',
  cod_enabled: '1', online_enabled: '0',  // online turns on once Paymob keys are added
  next_order_number: '1001',
  order_email: '',
};
for (const [key, value] of Object.entries(settings)) sql.push(insert('settings', { key, value: value || '' }));

for (const page of ['home', 'stories', 'menu', 'shop']) {
  sql.push(insert('seo_pages', {
    page,
    title_ar: I18N.ar[`meta.title.${page}`], title_en: I18N.en[`meta.title.${page}`],
    desc_ar: I18N.ar['meta.desc'], desc_en: I18N.en['meta.desc'],
    image: '/media/sign-close.jpg',
  }));
}
sql.push(insert('seo_pages', {
  page: 'store',
  title_ar: 'المتجر | بن السعودي', title_en: 'Store | El Soody Coffee',
  desc_ar: 'اطلب بن السعودي أونلاين: سادة أو محوّج أو فرنساوي، بالطحنة اللي تناسبك، استلام من المحل أو توصيل.',
  desc_en: 'Order El Soody coffee online: plain, spiced or French, ground your way, for pickup or delivery.',
  image: '/media/sign-close.jpg',
}));

writeFileSync(new URL('./seed.sql', import.meta.url), sql.join('\n') + '\n');
console.log(`seed.sql: ${pid} products, ${itemId} menu rows`);
